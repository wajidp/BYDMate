#!/usr/bin/env python3
"""BYDMate+: the fork's GitHub front page in English.

GitHub shows .github/README.md in place of the root README.md, so the fork gets an English
front page without touching upstream's README.md (Russian), which would conflict on every sync.
The page is upstream's README.en.md with relative links re-pointed from .github/ to the repo
root and a short BYDMate+ note on top. sync-release.yml re-runs this after each rebase.

Usage: scripts/plus-english-readme.py [repo root]   (writes <root>/.github/README.md)
"""
import pathlib
import re
import sys

NOTE = """> **BYDMate+** is a fork of [AndyShaman/BYDMate](https://github.com/AndyShaman/BYDMate) that follows
> every upstream release and adds a few extras (Keep AEB off, play-audio automation action).
> Builds: [Releases](https://github.com/wajidp/BYDMate/releases). Everything below is the upstream
> English README.

"""

# A link target that is not absolute (scheme, //host, /root) and not an in-page anchor.
RELATIVE = r"(?![a-zA-Z][a-zA-Z0-9+.-]*:|/|#)"


def to_github_dir(text: str) -> str:
    text = re.sub(r"\]\(" + RELATIVE, "](../", text)
    return re.sub(r'\b(src|href)="' + RELATIVE, r'\1="../', text)


def main() -> None:
    root = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else ".")
    source = (root / "README.en.md").read_text(encoding="utf-8")
    out = root / ".github" / "README.md"
    out.write_text(
        "<!-- Generated by scripts/plus-english-readme.py from README.en.md; do not edit. -->\n"
        + NOTE + to_github_dir(source),
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
